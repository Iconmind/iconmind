/**
 * Laravel via Blade Icons: no components to generate, just the SVGs laid out the way
 * blade-icons expects — flat names, the outline-regular cell as the bare name and every
 * other cell as a suffix.
 */
const bladeDir = fromRoot("packages/blade/resources/svg");
if (existsSync(bladeDir.replace("/resources/svg", ""))) {
  await rm(bladeDir, { recursive: true, force: true });
  await mkdir(bladeDir, { recursive: true });
  const { copyFile } = await import("node:fs/promises");
  let n = 0;
  for (const icon of icons) {
    for (const c of icon.cells) {
      const key = cellName(c.variant, c.weight);
      const name =
        key === "outline-regular" ? icon.slug :
        key === "duotone-regular" ? `${icon.slug}-duotone` :
        `${icon.slug}-${key}`;
      await writeFile(`${bladeDir}/${name}.svg`, c.svg);
      n++;
    }
  }
  console.log(`${bladeDir} — ${n} svgs for blade-icons`);
}
